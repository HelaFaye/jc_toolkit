"""Writes switch/source/tables.h from the Python app's data: the HD Rumble amplitude tables
(jctool/tables.py, for decoding .jcvib files) and the color presets (jctool/presets.py). Run
it from the repo root after changing either."""
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, ROOT)
from jctool import presets, tables  # noqa: E402


def array(ctype, name, values, fmt):
    rows = [", ".join(fmt % v for v in values[i:i + 10]) for i in range(0, len(values), 10)]
    return "static const %s %s[%d] __attribute__((unused)) = {\n    %s,\n};\n" % (ctype, name, len(values), ",\n    ".join(rows))


out = ["// Generated by tools/gen_switch_tables.py from jctool/tables.py. Don't edit.\n#pragma once\n#include <switch.h>\n",
       array("float", "AMP_FLOAT", tables.AMP_FLOAT, "%.6ff"),
       array("u8", "AMP_HA", tables.AMP_HA, "0x%02X"),
       array("u16", "AMP_LA", tables.AMP_LA, "0x%04X")]


def colors(rgbs):
    return ", ".join("{0x%02X, 0x%02X, 0x%02X}" % rgb for rgb in rgbs)


def preset_array(name, items):
    """Preset {name, colors[4]}: body, buttons (or left, right grip), [left grip, right grip]."""
    rows = ['    {"%s", {%s}},' % (item[0], colors(item[1:])) for item in items]
    return "static const Preset %s[] __attribute__((unused)) = {\n%s\n};\n#define N_%s (int)(sizeof(%s) / sizeof(%s[0]))\n" % (
        name, "\n".join(rows), name, name, name)


out += ["typedef struct {\n    const char *name;\n    u8 c[4][3];\n} Preset;\n",
        preset_array("RETAIL", presets.RETAIL), preset_array("EDITIONS", presets.EDITIONS),
        preset_array("GRIPS", presets.GRIPS), preset_array("PRO", presets.PRO)]
with open(os.path.join(ROOT, "switch", "source", "tables.h"), "w") as f:
    f.write("\n".join(out))
